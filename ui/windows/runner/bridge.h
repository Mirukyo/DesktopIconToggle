#pragma once

#include <windows.h>

#include <flutter/binary_messenger.h>

// ============================================================
// NativeBridge
// ============================================================

class NativeBridge
{
public:

    // --------------------------------------------------------
    // 注册 Flutter MethodChannel
    // --------------------------------------------------------

    static void Register(
        flutter::BinaryMessenger* messenger
    );

    // --------------------------------------------------------
    // 设置 Flutter Runner 原生窗口句柄
    // --------------------------------------------------------

    static void SetMainWindow(
        HWND window
    );

    // --------------------------------------------------------
    // 处理 Windows 原生窗口消息
    // --------------------------------------------------------

    static bool HandleWindowMessage(
        UINT message,
        WPARAM wparam
    );

    // --------------------------------------------------------
    // 请求真正退出应用
    // --------------------------------------------------------

    static bool RequestExit();

    // --------------------------------------------------------
    // 清理 NativeBridge
    // --------------------------------------------------------

    static void Shutdown();
};

